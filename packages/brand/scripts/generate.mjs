// Reads svg/**/*.svg and writes src/generated.ts. Plain Node, no bundler.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const list = (dir) =>
  readdirSync(join(root, 'svg', dir))
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((f) => [f.slice(0, -4), readFileSync(join(root, 'svg', dir, f), 'utf8')]);

const entries = (rows) =>
  rows.map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},\n`).join('');

function render() {
  const piko = list('.').map(([n, s]) => [n.replace(/^piko-/, ''), s]);
  return [
    '// Generated by scripts/generate.mjs from svg/**/*.svg. Do not edit.',
    '',
    `export const pikoSvg = {\n${entries(piko)}} as const;`,
    '',
    `export const iconSvg = {\n${entries(list('icons'))}} as const;`,
    '',
    'export type PikoMood = keyof typeof pikoSvg;',
    'export type IconName = keyof typeof iconSvg;',
    '',
  ].join('\n');
}

// `--stdout` prints instead of writing (used by the staleness test).
if (process.argv.includes('--stdout')) {
  process.stdout.write(render());
} else {
  writeFileSync(join(root, 'src', 'generated.ts'), render());
}
